import customtkinter as ctk


class TutorialFrame(ctk.CTkScrollableFrame):
    """
    Tutorial and Help Guide Frame explaining all options and workflows in Mouseframe Organizer.
    """

    def __init__(self, master, **kwargs):
        super().__init__(master, **kwargs)

        self._build_content()

    def _build_content(self):
        # Title
        title = ctk.CTkLabel(
            self,
            text="📖 Mouseframe Organizer - User Guide & Tutorial",
            font=ctk.CTkFont(size=20, weight="bold")
        )
        title.pack(anchor="w", padx=15, pady=(15, 10))

        intro_text = (
            "Welcome to the Mouseframe Data Organizer! This application automatically cleans, "
            "organizes, and formats gait analysis Excel files exported from Mouseframe software. "
            "Below is a complete explanation of every feature, setting, and input option."
        )
        intro = ctk.CTkLabel(self, text=intro_text, wraplength=820, justify="left")
        intro.pack(anchor="w", padx=15, pady=(0, 15))

        # Section 1: File Inputs
        self._add_section(
            title="1. File Inputs & Outputs",
            content=[
                ("Raw Mouseframe Excel File (.xlsx)",
                 "The raw Excel workbook generated by Mouseframe footprint tracking software. "
                 "The app scans every sheet for tables starting with 'Table ID:' and extracts metrics like stride length, overlap, and stride width."),
                ("Metadata Mapping File (Optional - CSV/Excel)",
                 "A secondary CSV or Excel file containing subject metadata with 3 columns: [Subject ID, Genotype, Sex].\n"
                 "Example Mapping Table:\n"
                 "  Subject ID | Genotype | Sex\n"
                 "  M01        | Wildtype | Male\n"
                 "  M02        | Knockout | Female\n\n"
                 "The app matches the Subject ID string against the Table IDs in your raw data."),
                ("Output Directory (Optional)",
                 "Where the organized Excel workbook will be saved. If left blank, it automatically saves to the same folder as your input file with a timestamped name.")
            ]
        )

        # Section 2: Visual Grouping Styles
        self._add_section(
            title="2. Visual Grouping Styles",
            content=[
                ("Pastel Header Tag + Explicit Columns (Recommended)",
                 "Adds explicit columns for Genotype, Sex, and Group. Applies soft pastel colors ONLY to the Genotype tag cells, "
                 "leaving the numeric data cells clean on white background for high readability."),
                ("Explicit Columns Only (Clean White Grid)",
                 "Adds explicit Genotype, Sex, and Group columns without any cell background fills. "
                 "This creates a clean data grid ready for instant copy-pasting or importing into GraphPad Prism, R, or SPSS."),
                ("Soft Pastel Row Fills",
                 "Applies muted pastel background fills across entire rows based on Genotype and Sex. "
                 "Uses high-contrast pastel colors that avoid obscuring numeric text.")
            ]
        )

        # Section 3: Processing Options
        self._add_section(
            title="3. Processing & Calculation Settings",
            content=[
                ("Unit Conversion Threshold (Default: 500.0)",
                 "Raw Mouseframe output sometimes exports values in millimeters or micrometers (e.g. 620.0). "
                 "If a metric value exceeds this threshold, the app automatically divides it by 1000.0 (converting 620.0 to 0.620 cm)."),
                ("Automated Summary Sheet Per Animal (Summary_Per_Animal)",
                 "When checked, the app automatically creates a consolidated 'Summary_Per_Animal' sheet as the first tab in your Excel file.\n"
                 "Every row represents ONE animal at ONE timepoint (with Table ID, Timepoint, Genotype, Sex, Group), followed by all calculated gait metric averages. "
                 "This provides a master table ready for data extraction and statistical analysis.")
            ]
        )

        # Section 4: Data Preview & Actions
        self._add_section(
            title="4. Data Preview & Action Buttons",
            content=[
                ("🔍 Preview Data Button",
                 "Parses your raw Excel file and displays a live validation table below without generating a new file. "
                 "Matched subjects highlight in green, while unmapped subjects highlight in soft red so you can spot missing IDs."),
                ("🚀 Process & Export Excel Button",
                 "Runs the full organization pipeline, applies your chosen visual style, generates the summary per animal sheet, "
                 "and prompts you to open the output folder when complete.")
            ]
        )

    def _add_section(self, title, content):
        card = ctk.CTkFrame(self, corner_radius=8)
        card.pack(fill="x", padx=15, pady=10)

        sec_title = ctk.CTkLabel(card, text=title, font=ctk.CTkFont(size=15, weight="bold"))
        sec_title.pack(anchor="w", padx=15, pady=(12, 8))

        for heading, body in content:
            h_label = ctk.CTkLabel(card, text=f"• {heading}", font=ctk.CTkFont(weight="bold"), text_color="#2980B9")
            h_label.pack(anchor="w", padx=20, pady=(4, 1))

            b_label = ctk.CTkLabel(card, text=body, wraplength=780, justify="left")
            b_label.pack(anchor="w", padx=35, pady=(0, 8))
